"""gen_tables.py <t1_dir> <out_md> : Markdown tables from t1_log.json, metrics_t1.json and metrics_lowres.json (numbers copied, not re-typed)."""
import sys, os, json

T, OUT = sys.argv[1], sys.argv[2]
log = json.load(open(os.path.join(T, 't1_log.json')))
m = json.load(open(os.path.join(T, 'metrics', 'metrics_t1.json')))
lo = json.load(open(os.path.join(T, 'metrics', 'metrics_lowres.json')))
L = []
L.append('# T1 measurement tables (generated by gen_tables.py)\n')
L.append('## Shot timing (seconds after the camera move; session time)\n')
L.append('| view | tag | requested | done | session |\n|---|---|---|---|---|')
for s in log['shots']:
    if 'requested_after_move_s' in s:
        L.append('| %s | %s | %.2f | %.2f | %.1f |' % (s['view'], s['tag'], s['requested_after_move_s'], s['done_after_move_s'], s['session_s']))
L.append('\n## Full-resolution metrics (1920x1080)\n')
L.append('SSIM: 1 = identical. UE Low = Unreal automation screenshot comparison (Low tolerance, ignore-AA, global <= 0.02, local <= 0.10) re-implemented.\n')
L.append('| set | A | B | SSIM | SSIM UE 8x8 | PSNR dB | MAE | p99 | UE Low global | UE Low local | UE Low |\n|---|---|---|---|---|---|---|---|---|---|---|')
for k in ('static', 'revisit', 'settle_vs_last'):
    for r in m[k]:
        u = r['ue_low']
        L.append('| %s | %s | %s | %.4f | %.4f | %s | %.2f | %d | %.4f | %.4f | %s |' % (k, r['a'][:-4], r['b'][:-4], r['ssim_g'], r['ssim_ue8'], r['psnr_db'], r['mae'], r['p99_absdiff'],
                                                                                      u['global'], u['max_local'], 'PASS' if u['pass'] else 'FAIL'))
r = m['self_check']
L.append('| self-check | %s | %s | %.4f | %.4f | %s | %.2f | %d | %.4f | %.4f | %s |' % (r['a'][:-4], r['b'][:-4], r['ssim_g'], r['ssim_ue8'], r['psnr_db'], r['mae'], r['p99_absdiff'],
                                                                                        r['ue_low']['global'], r['ue_low']['max_local'], 'PASS' if r['ue_low']['pass'] else 'FAIL'))
L.append('\n## Scale-reduced metrics (noise floor)\n')
L.append('d8/d16 = box-downsampled by 8/16; tile = 16x9 grid mean luma (0-255); global = mean-luma change.\n')
L.append('| view | kind | A | B | SSIM d8 | SSIM d16 | MAE d16 | tile max | tile mean | global |\n|---|---|---|---|---|---|---|---|---|---|')
for r in lo['pairs']:
    L.append('| %s | %s | %s | %s | %.4f | %.4f | %.2f | %.2f | %.2f | %+.2f |' % (r['view'], r['kind'], r['a'].split('__')[1][:-4], r['b'].split('__')[1][:-4], r['ssim_d8'], r['ssim_d16'],
                                                                             r['mae_luma_d16'], r['tile_luma_max'], r['tile_luma_mean'], r['global_luma_diff']))
L.append('\n## Synthetic-change sensitivity (image-space edits of B_round3; the scene was not changed)\n')
L.append('| view | change | SSIM d8 | SSIM d16 | tile max | global |\n|---|---|---|---|---|---|')
for r in lo['synthetic']:
    L.append('| %s | %s | %.4f | %.4f | %.2f | %+.2f |' % (r['view'], r['change'], r['ssim_d8'], r['ssim_d16'], r['tile_luma_max'], r['global_luma_diff']))
open(OUT, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print('TABLES', OUT)
