"""gen_tables_t1b.py <t1b_dir> <out_md> : Markdown tables from t1b_log.json, t1b_metrics.json, t1b_detect_pair.json, t1b_detect_rich.json, abp_inspect.json, pie_log.json."""
import sys, os, json

T, OUT = sys.argv[1], sys.argv[2]
J = lambda *p: json.load(open(os.path.join(T, *p)))
log, m = J('t1b_log.json'), J('metrics', 't1b_metrics.json')
L = ['# T1b / ABP / player-camera tables (generated by gen_tables_t1b.py)\n']

a = J('abp_inspect.json')
L.append('## Dirty AnimBlueprints (read-only inspection)\n')
L.append('| ABP | dirty | disk = last V2.40 write | BP status | key | production (disk) | in memory | equal |\n|---|---|---|---|---|---|---|---|')
for p, r in a['abps'].items():
    for k, v in r['harness_touched_keys'].items():
        L.append('| %s | %s | %s | %s | %s | %s | %s | %s |' % (p.rsplit('/', 1)[-1], r['dirty'], r['disk_equals_last_v240_write'], r['bp_status'].split('.')[-1].split(':')[0],
                                                       k, str(v['production']).rsplit('/', 1)[-1], str(v['current']).rsplit('/', 1)[-1], v['equal']))

L.append('\n## Real reversible changes (editor-only temporary hide; dirty packages and transforms unchanged)\n')
L.append('| view | size | actor label | class | half-extent cm | distance cm | screen box (1920x1080) |\n|---|---|---|---|---|---|---|')
for v, pk in log['picks'].items():
    if not pk:
        L.append('| %s | - | no visible candidate passed the filter | | | | |' % v)
    for sz, d in pk.items():
        L.append('| %s | %s | %s | %s | %s | %s | %s |' % (v, sz, d['label'], d['class'], d['max_half_extent_cm'], d['distance_cm'], d['screen_box_1920x1080']))

L.append('\n## Mean luma per frame (global step = capture-cadence state, not smooth adaptation)\n')
L.append('| view | set | f0 | f1 | f2 | f3 | f4 |\n|---|---|---|---|---|---|---|')
for v, V in m['views'].items():
    for n, xs in V['mean_luma_per_frame'].items():
        L.append('| %s | %s | %s |' % (v, n, ' | '.join('%.2f' % x for x in xs)))

L.append('\n## Noise sources, within-set consecutive frames (~1 s apart; estimate, heuristic masks)\n')
L.append('| view | exposure (global) | shadow LF (non-green) | HF residual on non-green (TSR + non-green foliage + shadow edges) | green vegetation | rms luma | green pixel fraction |\n|---|---|---|---|---|---|---|')
for v, V in m['views'].items():
    f = V['noise_sources_within_set']['fraction_of_energy']; n = V['noise_sources_within_set']
    L.append('| %s | %.1f %% | %.1f %% | %.1f %% | %.1f %% | %.2f | %.2f |' % (v, 100 * f['exposure'], 100 * f['shadow_lf'], 100 * f['aa_hf'], 100 * f['foliage'], n['rms_luma_total'], n['vegetation_pixel_fraction']))

L.append('\n## Median of 5 vs single frame (no normalisation; tile16 = 16x9, tile48 = 48x27 max |Δ mean luma|)\n')
L.append('| view | pair | median tile16 | median tile48 | median SSIM d8 | single mean tile16 | single worst tile16 | single mean SSIM d8 |\n|---|---|---|---|---|---|---|---|')
for v, V in m['views'].items():
    for p, r in V['pairs'].items():
        L.append('| %s | %s | %.2f | %.2f | %.4f | %.2f | %.2f | %.4f |' % (v, p, r['median']['tile16'], r['median']['tile48'], r['median']['ssim_d8'],
                                                                     r['single_mean']['tile16'], r['single_worst']['tile16'], r['single_mean']['ssim_d8']))

for model in ('pair', 'rich'):
    p = os.path.join(T, 'metrics', 't1b_detect_%s.json' % model)
    if not os.path.exists(p):
        continue
    d = json.load(open(p))
    L.append('\n## Tile z-score detector, noise model "%s" (exposure-normalised, 48x27 tiles)\n' % model)
    L.append('| view | mode | case | z in changed tiles | max z (anywhere) | localised | detected z>3 | detected z>5 |\n|---|---|---|---|---|---|---|---|')
    for v, V in d.items():
        for mode, M in V.items():
            fa = M['false_alarm_S2_S5']
            L.append('| %s | %s | NO CHANGE S2-S5 | - | %.2f | - | %d tiles > 3 | %d tiles > 5 |' % (v, mode, fa['max_z'], fa['false_tiles_z3'], fa['false_tiles_z5']))
            for k in [k for k in M if k.startswith('real_')]:
                r = M[k]
                L.append('| %s | %s | %s | %.2f | %.2f | %s | %s | %s |' % (v, mode, k, r['z_in_change_tiles'], r['max_z'], r['localised'], r['detect_z3'], r['detect_z5']))
            for k, r in M['injected_patch_swap'].items():
                L.append('| %s | %s | injected %s (tile noise %.2f) | %.2f | %.2f | %s | %s | %s |' % (v, mode, k, r['tile_noise'], r['z_in_change_tiles'], r['max_z'], r['localised'], r['detect_z3'], r['detect_z5']))

if os.path.exists(os.path.join(T, 'pie_log.json')):
    pl = J('pie_log.json')
    L.append('\n## Player-camera stills (PIE, real pawn + GraceRanger camera)\n')
    L.append('pawn %s, camera manager %s, view target %s\n' % (pl.get('pawn_class'), pl.get('camera_manager'), pl.get('view_target')))
    L.append('| station | dir | camera FOV | camera loc | camera rot (p,y,r) | pawn loc | camera-pawn cm | pawn speed |\n|---|---|---|---|---|---|---|---|')
    for s in pl['shots']:
        L.append('| %s | %s | %s | %s | %s | %s | %s | %s |' % (s['station'], s['dir'], s['camera_fov'], s['camera_loc'], s['camera_rot_pyr'], s['pawn_loc'], s['camera_to_pawn_cm'], s['pawn_speed']))
    L.append('\nteleports: ' + json.dumps(pl['events']))
open(OUT, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print('TABLES', OUT)
